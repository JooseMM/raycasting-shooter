fn draw_tiles(handler: &mut RaylibDrawHandle, map: &[[u8; 24]; 24]) {
    let p_width = SCREEN_WIDTH / 24;
    let p_height = SCREEN_HEIGHT / 24;

    let mut next_x = 0;
    let mut next_y = 0;

    for line in map {
        for p in line {
            if *p > 0 {
                handler.draw_rectangle(next_x, next_y, p_width, p_height, Color::BROWN);
            } else {
                handler.draw_rectangle_lines(next_x, next_y, p_width, p_height, Color::BROWN);
            }

            next_x += p_width;
        }

        next_x = 0;
        next_y += p_height;
    }
}
